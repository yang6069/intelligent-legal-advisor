# 五、种子导入入口
# ==================================================================
def seed_knowledge(force: bool = False) -> dict:
    """
    导入种子知识数据（幂等）。

    参数:
        force: True 时清空后重新导入（重置场景）

    逻辑:
        1. 检查 kb_documents 已有记录数，非空且未 force 则跳过；
        2. 批量 INSERT IGNORE（唯一键 doc_type+title+article_no 防重）；
        3. 返回导入统计。

    返回: {"imported": 新增数, "total": 总数, "skipped": bool}
    """
    try:
        existing = database.query_one("SELECT COUNT(*) AS c FROM kb_documents")["c"]
        if existing > 0 and not force:
            return {"imported": 0, "total": existing, "skipped": True}

        if force:
            database.execute("DELETE FROM kb_documents")

        rows = []
        # 法律法规
        for law_name, article_no, content in LAWS:
            rows.append(("law", f"{law_name}{article_no}", law_name,
                         article_no, content, "有效"))
        # 司法解释
        for name, article_no, content in INTERPRETATIONS:
            rows.append(("interpretation", f"{name}{article_no}", name,
                         article_no, content, "有效"))
        # 裁判案例
        for title, content in CASES:
            rows.append(("case", title, "", "", content, "有效"))
        # 合同模板
        for title, content in TEMPLATES:
            rows.append(("template", title, "", "", content, "有效"))

        for doc_type, title, law_name, article_no, content, eff in rows:
            database.execute(
                "INSERT IGNORE INTO kb_documents "
                "(doc_type, title, law_name, article_no, content, "
                "effectiveness, char_count, source, indexed) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s, '内置种子知识库', 0)",
                (doc_type, title, law_name, article_no, content, eff,
                 len(content)))
        total = database.query_one("SELECT COUNT(*) AS c FROM kb_documents")["c"]
        logger.info("种子知识导入完成：%d 条（总计 %d）", len(rows), total)
        return {"imported": len(rows), "total": total, "skipped": False}
    except Exception as e:
        logger.warning("种子知识导入失败（数据库未就绪?）: %s", e)
        return {"imported": 0, "total": 0, "skipped": True, "error": str(e)}
